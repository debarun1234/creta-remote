#!/usr/bin/env python3
"""Regenerates app/.../ui/CarPaths.kt from the SVG path data in tools/art/*.json."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent
out = root.parent / "app/src/main/java/com/debarun/cretaremote/ui/CarPaths.kt"
side = json.loads((root / "art/side.json").read_text())
top = json.loads((root / "art/top.json").read_text())

def block(name, data):
    lines = [f'    /** SVG path data, design space of the {name} view. */', f'    object {name.capitalize()} {{']
    for k, v in data.items():
        lines.append(f'        const val {k.upper()} = "{v}"')
    lines.append('    }')
    return "\n".join(lines)

out.write_text("// GENERATED by tools/gen_car_paths.py - do not edit by hand.\npackage com.debarun.cretaremote.ui\n\nobject CarPaths {\n"
               + block("side", side) + "\n\n" + block("top", top) + "\n}\n")
print("wrote", out)
